"""Generate REPORT.md: optimization results on team-created test circuits.

Run:  python report.py            (writes REPORT.md; a few minutes)

Every number in the report is produced here, by calling `optimize` from
submission.py and checking it with the organizers' own functions
(equivalent_up_to_global_phase, circuit_metrics, circuit_cost).
Deterministic: fixed circuits and seeds.
"""
import random
import time

import bench
import stage2_baseline
from submission import (circuit_cost, circuit_metrics, equivalent_up_to_global_phase,
                        optimize)

W2 = {"w1": 1.0, "w2": 6.0, "wd": 0.2}     # the guidelines' example weights
PROFILES = bench.PROFILES
TOFFOLI = [(g, *q) for g, q in bench.TOFFOLI]      # (name, qubit, ...) tuples for C()


def C(n, *gates):
    return {"n_qubits": n, "gates": [{"gate": g, "qubits": list(q)} for g, *q in gates]}


def fmt(circuit, limit=40):
    gs = [f"{g['gate']}{''.join(map(str, g['qubits']))}" for g in circuit["gates"]]
    if not gs:
        return "(empty: identity)"
    text = " ".join(gs[:limit])
    return text + (f" ... (+{len(gs) - limit} more)" if len(gs) > limit else "")


def metrics(c):
    m = circuit_metrics(c)
    return f"{m['n_1q']} / {m['n_2q']} / {m['depth']}"


def case(title, circuit, config, technique, out_lines):
    start = time.perf_counter()
    out = optimize(circuit, config)
    secs = time.perf_counter() - start
    ok = equivalent_up_to_global_phase(circuit, out)
    out_lines += [
        f"### {title}",
        "",
        f"- **Weights** (w1, w2, wd): ({config['w1']:g}, {config['w2']:g}, {config['wd']:g})",
        f"- **Input:** `{fmt(circuit)}`",
        f"- **Output:** `{fmt(out)}`",
        f"- **Equivalent up to global phase (organizers' checker):** {'yes' if ok else 'NO'}",
        f"- **1q / 2q / depth:** {metrics(circuit)} -> {metrics(out)}",
        f"- **Cost:** {circuit_cost(circuit, config):g} -> {circuit_cost(out, config):g}"
        f"  ({secs:.2f} s)",
        f"- **Why:** {technique}",
        "",
    ]
    return ok


def main():
    lines = [
        "# Optimization Results Report",
        "",
        "Generated by `python report.py` from `submission.py`. Every circuit is",
        "checked with the organizers' `equivalent_up_to_global_phase`, and resources",
        "are measured with their `circuit_metrics` and `circuit_cost`.",
        "**1q / 2q / depth** = single-qubit gates / CX gates / circuit depth.",
        "See README.md for the algorithm and the identities named below.",
        "",
    ]
    all_ok = True

    lines += ["## Level 1: basic cancellation", ""]
    all_ok &= case("Self-inverse pairs and inverse phases",
                   C(1, ("H", 0), ("H", 0), ("X", 0), ("X", 0), ("T", 0), ("TDG", 0)), W2,
                   "H H = X X = T TDG = I (identity 1), removed by the per-wire stacks (Stage 1).",
                   lines)
    all_ok &= case("A phase run that only collapses when summed",
                   C(1, ("T", 0), ("Z", 0), ("T", 0)), W2,
                   "T Z T = T^(1+4+1) = T^6 = SDG (identity 2). No adjacent pair cancels; summing the run does.",
                   lines)

    lines += ["## Level 2: hidden (non-adjacent) redundancies", ""]
    all_ok &= case("The guidelines' example", C(2, ("CX", 0, 1), ("Z", 0), ("CX", 0, 1)), W2,
                   "Z on the control commutes with CX (identity 9), so the CX pair meets and cancels.",
                   lines)
    all_ok &= case("X on the target", C(2, ("CX", 0, 1), ("X", 1), ("CX", 0, 1)), W2,
                   "X on the target commutes with CX (identity 10).", lines)
    all_ok &= case("CX gates sharing a control", C(3, ("CX", 0, 1), ("CX", 0, 2), ("CX", 0, 1)), W2,
                   "CX01 and CX02 commute (identity 11); the CX01 pair cancels.", lines)
    all_ok &= case("A phase through a CX control", C(2, ("T", 0), ("CX", 0, 1), ("T", 0)), W2,
                   "T is diagonal, so it passes the CX control; the segment sums to S (identities 2 and 9).",
                   lines)
    all_ok &= case("Sandwich identities", C(1, ("H", 0), ("X", 0), ("H", 0), ("X", 0), ("T", 0), ("X", 0)), W2,
                   "H X H = Z and X T X = TDG up to phase (identities 3 and 4), then Z TDG = T^3 = S T (identity 2); found by the exact one-qubit run table.",
                   lines)

    lines += ["## Level 3: general compiler cases", ""]
    all_ok &= case("Toffoli twice (7-T decomposition): the identity", C(3, *(TOFFOLI + TOFFOLI)), W2,
                   "The middle H gates cancel, leaving one H-free region equal to CCZ*CCZ = I: its phase "
                   "table is all zero, so the canonical rebuild is empty (identities 16 and 18). Stage 2 "
                   "alone only reaches 27 gates.", lines)
    rng = random.Random(7)
    r = bench._rand(rng, 3, 14, ["CX", "X", "Z", "S", "SDG", "T", "TDG"])
    inv = {"S": "SDG", "SDG": "S", "T": "TDG", "TDG": "T"}
    cu = r + [("H", (3,))] + [(inv.get(g, g), q) for g, q in reversed(r)]
    all_ok &= case("Compute, unrelated H, uncompute", C(4, *[(g, *q) for g, q in cu]), W2,
                   "The H acts on a wire neither half touches, so both halves form one region, which is the identity.",
                   lines)
    all_ok &= case("Hadamard-reversed CX", C(2, ("H", 0), ("H", 1), ("CX", 0, 1), ("H", 0), ("H", 1)), W2,
                   "(H x H) CX01 (H x H) = CX10 (identity 14), found by the exact two-qubit Clifford table.",
                   lines)
    all_ok &= case("Phase folding across H gates",
                   C(3, ("CX", 0, 1), ("T", 1), ("H", 0), ("T", 0), ("H", 0), ("CX", 1, 2),
                     ("CX", 1, 2), ("T", 1)), W2,
                   "Wire 1 holds x0 XOR x1 throughout; the two T gates on it merge into S even though H gates "
                   "sit between them (identity 20).", lines)
    rng = random.Random(11)
    big = bench._rand(rng, 5, 60, sorted(bench.s4.ALLOWED_GATES))
    all_ok &= case("A random 5-qubit, 60-gate circuit", C(5, *[(g, *q) for g, q in big]), W2,
                   "Many interacting rewrites (cancellation, regions, blocks, beam search).", lines)

    lines += ["## Level 4: adapting to the weights", "",
              "The same circuit under different weights gives different outputs:", ""]
    z = C(2, ("CX", 0, 1), ("Z", 1), ("CX", 0, 1))
    for name, cfg, why in (
            ("CX-heavy", {"w1": 1.0, "w2": 6.0, "wd": 0.2},
             "CX Z1 CX = Z0 Z1 (identity 13) removes two CX for one extra one-qubit gate: worth it here."),
            ("one-qubit only", {"w1": 1.0, "w2": 0.0, "wd": 0.0},
             "CX gates are free, so the 1-gate original beats Z0 Z1 (2 one-qubit gates) and is kept.")):
        all_ok &= case(f"CX Z1 CX under {name} weights", z, cfg, why, lines)
    rng = random.Random(3)
    g = bench._rand(rng, 4, 40, sorted(bench.s4.ALLOWED_GATES))
    circuit = C(4, *[(x, *q) for x, q in g])
    lines += ["One random 4-qubit circuit under all four benchmark profiles:", "",
              "| Weights | 1q / 2q / depth (input -> output) | Cost (input -> output) | Equivalent |",
              "|---|---|---|---|"]
    for pname, cfg in PROFILES.items():
        out = optimize(circuit, cfg)
        ok = equivalent_up_to_global_phase(circuit, out)
        all_ok &= ok
        lines.append(f"| {pname} | {metrics(circuit)} -> {metrics(out)} | "
                     f"{circuit_cost(circuit, cfg):g} -> {circuit_cost(out, cfg):g} | {'yes' if ok else 'NO'} |")
    lines.append("")

    lines += ["## Where it struggles or cannot improve", ""]
    all_ok &= case("A single Toffoli", C(3, *TOFFOLI), W2,
                   "Still 7 T and 6 CX gates, the known minima (Gosset et al. 2013; Shende & Markov 2008); "
                   "only the arrangement changed, lowering depth (cost 47.2 -> 46.8).", lines)
    all_ok &= case("SWAP", C(2, ("CX", 0, 1), ("CX", 1, 0), ("CX", 0, 1)), W2,
                   "Unchanged: SWAP needs 3 CX gates (the exact two-qubit table confirms no cheaper form).",
                   lines)
    lines += ["Other known limits (measured, see README section 9):",
              "- On 2-qubit circuits with a known optimum of at most 4 gates, 2 of 524 are 1 gate above optimal.",
              "- Regions of 4-6 wires use heuristic CX synthesis, so wide CX networks may not be minimal.",
              "- Large random circuits keep most of their structure: the beam search finds local improvements,"
              " not global optima.", ""]

    lines += ["## Corpus results (35 circuits, 4 weight profiles)", "",
              "| Weights | Mean cost: input | Stage 1-2 baseline | submission.py | vs input | vs baseline | all equivalent |",
              "|---|---|---|---|---|---|---|"]
    circuits = bench.corpus(8)
    for pname, cfg in PROFILES.items():
        tin = t2 = t4 = 0.0
        ok_all = True
        for _, n, gates in circuits:
            c = bench.s4._from_pairs(n, gates)
            out = optimize(c, cfg)
            ok_all &= equivalent_up_to_global_phase(c, out)
            tin += circuit_cost(c, cfg)
            t2 += circuit_cost(stage2_baseline.optimize(c, cfg), cfg)
            t4 += circuit_cost(out, cfg)
        all_ok &= ok_all
        k = len(circuits)
        lines.append(f"| {pname} | {tin / k:.2f} | {t2 / k:.2f} | {t4 / k:.2f} | {t4 / tin:.3f} | "
                     f"{t4 / t2:.3f} | {'yes' if ok_all else 'NO'} |")
    lines.append("")

    lines += ["## Runtime versus circuit size", "",
              "Mean seconds per `optimize` call on random 6-qubit circuits (weights 1, 6, 0.2):", "",
              "| Gates | Mean seconds | Mean cost reduction |", "|---|---|---|"]
    optimize(C(1, ("H", 0)), W2)        # build the tables first (one-time ~2 s)
    rng = random.Random(21)
    for size in (10, 20, 40, 60):
        secs = red = 0.0
        for _ in range(4):
            c = C(6, *[(x, *q) for x, q in bench._rand(rng, 6, size, sorted(bench.s4.ALLOWED_GATES))])
            start = time.perf_counter()
            out = optimize(c, W2)
            secs += time.perf_counter() - start
            all_ok &= equivalent_up_to_global_phase(c, out)
            red += 1 - circuit_cost(out, W2) / max(circuit_cost(c, W2), 1e-12)
        lines.append(f"| {size} | {secs / 4:.2f} | {100 * red / 4:.0f}% |")
    lines += ["", f"**Every output in this report passed the organizers' equivalence check: "
              f"{'yes' if all_ok else 'NO'}.**", ""]

    with open("REPORT.md", "w") as f:
        f.write("\n".join(lines))
    print("wrote REPORT.md; all equivalent:", all_ok)


if __name__ == "__main__":
    main()
